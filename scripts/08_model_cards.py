"""Step 8: write the model card and the data card from the result tables.

Needs steps 1-5 (6 and 7 add sections when present). Writes Markdown so the cards
always match the latest run:

* ``docs/model_card_<mode>.md``: the engine's model, intended use, performance of
  every model with uncertainty, speed, explanations, monitoring, limits, maintenance;
* ``docs/data_card_<mode>.md``: source, period, cleaning with counts, sampling,
  category harmonisation, split, known issues.

Examples::

    python scripts/08_model_cards.py --mode full --set data.session_sample_fraction=0.1
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import base_parser, setup  # noqa: E402

import polars as pl  # noqa: E402

from src.config import PROJECT_ROOT  # noqa: E402
from src.serving.recommend import recommended  # noqa: E402
from src.serving.results import ResultStore  # noqa: E402

LABELS = {"rule_based": "Rule baseline", "logistic_regression": "Logistic regression", "random_forest": "Random forest",
          "lightgbm": "LightGBM", "mlp": "MLP", "tabnet": "TabNet", "gru": "GRU (sequence)"}
_ML, _DL = "machine learning, M. Kara", "deep learning, K. Ray"
TEAM = {"rule_based": _ML, "logistic_regression": _ML, "random_forest": _ML, "lightgbm": _ML,
        "mlp": _DL, "tabnet": _DL, "gru": _DL}


def n(v: float) -> str:
    return f"{v:,.0f}"


def table(rows: list[list[str]], head: list[str]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    return "\n".join(out + ["| " + " | ".join(r) + " |" for r in rows])


def model_card(store: ResultStore, cfg: dict, k: int) -> str:
    rq1 = store.csv("rq1_model_comparison")
    pairs, eff = store.csv("rq1_pairwise_tests"), store.csv("rq4_efficiency")
    data = store.json("data_summary") or {}
    ex = store.json("rq5_explain_summary") or {}
    mon = store.json("monitoring_summary") or {}
    if rq1 is None:
        raise SystemExit("No rq1_model_comparison table: run scripts/03_run_experiments.py first.")
    ship, tied = recommended(rq1, pairs, eff, k)
    part = rq1.filter(pl.col("k") == k).sort("pr_auc_mean", descending=True)
    r = part.filter(pl.col("model") == ship).row(0, named=True)
    sp = data["splits"][str(k)]
    clean = data.get("cleaning")
    seeds = int(part["n_seeds"].max())

    perf = [[LABELS[x["model"]] + (" **(engine)**" if x["model"] == ship else ""), TEAM[x["model"]],
             f"{x['pr_auc_mean']:.3f}" + (f" ± {x['pr_auc_std']:.3f}" if x["n_seeds"] > 1 else ""),
             f"{x['pr_auc_ci_low']:.3f}–{x['pr_auc_ci_high']:.3f}",
             f"{x['pr_auc_lift_mean']:.1f}×", f"{x['precision_mean']:.2f}", f"{x['recall_mean']:.2f}"]
            for x in part.iter_rows(named=True)]
    speed = []
    if eff is not None:
        for x in eff.filter(pl.col("k") == k).sort("latency_b1_p95_ms").iter_rows(named=True):
            speed.append([LABELS[x["model"]], f"{x['latency_b1_p95_ms']:.3f}", f"{x['throughput_b4096_per_sec']:,.0f}",
                          f"{x['model_size_mb']:.1f}"])
    by_k = []
    for kk in sorted(set(rq1["k"].to_list())):
        s, _ = recommended(rq1, pairs, eff, kk)
        x = rq1.filter((pl.col("k") == kk) & (pl.col("model") == s)).row(0, named=True)
        by_k.append([str(kk), LABELS[s], f"{x['pr_auc_mean']:.3f}", f"{x['pr_auc_lift_mean']:.1f}×"])

    missed = ex.get("buyers_missed_by_all")
    top = ", ".join(f"{t['feature']} ({t['mean_share']:.0%})" for t in ex.get("top_features", [])[:5])
    m = (mon.get("models") or {}).get(str(k), {}).get(ship)
    drift = (mon.get("drift") or {}).get(str(k))
    lines = [
        f"# Model card: Purchase Intent Engine ({cfg['data']['mode']} data, K = {k})",
        "",
        f"*Generated by `scripts/08_model_cards.py` on {date.today():%d %B %Y} from `results/tables`. Do not edit by hand.*",
        "",
        "## Model",
        f"- **Engine model:** {LABELS[ship]} ({TEAM[ship]}), chosen as the fastest of the models statistically tied "
        f"for the best PR-AUC at K = {k} ({', '.join(LABELS[t] for t in tied)}; paired bootstrap, Holm-corrected, α = 0.05).",
        f"- **Input:** the first {k} events (views and add-to-carts) of a visit: time, product, category, brand, price.",
        "- **Output:** a score in [0, 1], a buyer / non-buyer decision at a threshold tuned on the validation weeks "
        f"(F1), an intent level (high, warm, browsing) and a suggested action. At its threshold the engine model "
        f"reaches {r['precision_mean']:.2f} precision and {r['recall_mean']:.2f} recall on the test weeks.",
        "- **Serving:** `src/serving/predictor.py` (Python), `src/api/app.py` (REST, `POST /score`), dashboard "
        "Live scoring page. The same feature code is used in training and serving.",
        "",
        "## Intended use",
        "- Rank live visits by purchase intent to decide *who should not get a discount* (high intent buys anyway) "
        "and who gets a nudge. See the Campaign planner page for the money involved.",
        "- **Out of scope:** decisions about individuals with legal or similarly significant effects, credit, pricing "
        "per person, or any use outside the shop's own visitors. The score is not a calibrated probability.",
        "",
        "## Training data",
        (f"- REES46 multi-category shop, {clean['sources'][0].split('.')[0]} to {clean['sources'][-1].split('.')[0]}, "
         f"{clean['sessions_out'] / clean['sessions_in']:.0%} random sample of whole visits "
         f"({n(clean['sessions_out'])} visits, {n(clean['rows_out'])} events). See the data card.") if clean
        else f"- {cfg['data']['mode']} data; see the data card.",
        f"- Chronological split by visit start: train {sp['train']['first_start'][:10]} → {sp['train']['last_start'][:10]} "
        f"({n(sp['train']['sessions'])} visits), validation → {sp['val']['last_start'][:10]} ({n(sp['val']['sessions'])}), "
        f"test {sp['test']['first_start'][:10]} → {sp['test']['last_start'][:10]} ({n(sp['test']['sessions'])}, "
        f"{sp['test']['positive_rate']:.1%} buy).",
        "",
        "## Performance (test weeks)",
        (f"PR-AUC mean ± std over {seeds} seeds" if seeds > 1 else "PR-AUC from one seed")
        + "; 95 % CI from a bootstrap of the primary seed; "
        "lift = PR-AUC / buyer rate (random = 1×). Precision and recall at each model's tuned threshold.",
        "",
        table(perf, ["Model", "Team", "PR-AUC", "95% CI", "Lift", "Precision", "Recall"]),
        "",
        "Engine model per K:",
        "",
        table(by_k, ["K", "Engine model", "PR-AUC", "Lift"]),
        "",
    ]
    if speed:
        lines += ["## Speed and size (one CPU thread)", "",
                  table(speed, ["Model", "p95 latency, 1 visit (ms)", "Visits/s in batches of 4,096", "Size (MB)"]), ""]
    lines += ["## Explanations", f"- Most influential features across models (share of attribution): {top}."
              if top else "- Run `scripts/06_explain.py` for attributions."]
    if ex.get("H5"):
        lines.append(f"- Cart signals are the top feature group for {ex['H5'].get('cart_group_top', '?')} model × K "
                     "combinations.")
    lines += ["- LightGBM per-visit explanations (TreeSHAP) are returned by the API with `explain: true`.", ""]
    if m or drift:
        lines += ["## Monitoring (validation and test weeks)"]
        if m:
            lines.append(f"- Weekly PR-AUC of the engine model: {m['pr_auc_min']:.3f}–{m['pr_auc_max']:.3f} over "
                         f"{m['weeks']} weeks; lift {m['lift_min']:.1f}×–{m['lift_max']:.1f}×. Weekly accuracy follows the "
                         "weekly buyer rate.")
        if drift:
            lines.append(f"- Input drift (PSI vs training): major in {', '.join(drift['major']) or 'no feature'}; "
                         f"moderate in {', '.join(drift['moderate']) or 'no feature'}.")
        lines.append("- Alert rule: weekly 95 % CI below the test PR-AUC for two weeks, or any PSI > 0.25.")
        lines.append("")
    lines += [
        "## Limitations",
        f"- {missed['n'] / missed['of']:.0%} of test buyers ({n(missed['n'])} of {n(missed['of'])}) show no buying "
        "signal in their first clicks and are missed by every model." if missed else "",
        "- Scores rank visits but are not calibrated probabilities (models were trained with class balancing).",
        "- One shop, Oct 2019 – Apr 2020: patterns may differ in other shops, seasons or after site changes.",
        "- REES46 changed its category tree in December 2019; labels were mapped back to the Oct/Nov tree "
        "(data card). Products with no category stay `unknown`.",
        "- The campaign planner's money figures depend on an assumed offer effect; measure it with an A/B test.",
        "",
        "## Ethical considerations",
        "- Inputs are behavioural events of an anonymous visit; no names, contact details or demographics are used. "
        "`user_id` is not a model input.",
        "- Withholding a discount from high-intent visitors changes what different visitors are offered; the shop "
        "should make sure offers stay within its pricing and consumer-protection rules.",
        "",
        "## Maintenance",
        "- Retrain monthly on a rolling window (`scripts/01`–`03`), rerun benchmarks, monitoring and these cards "
        "(`scripts/05`, `07`, `08`).",
        "- Owners: machine-learning models M. Kara; deep-learning models K. Ray.",
    ]
    return "\n".join(x for x in lines if x is not None) + "\n"


def data_card(store: ResultStore, cfg: dict) -> str:
    d = store.json("data_summary") or {}
    clean = d.get("cleaning") or {}
    if not clean:
        return (f"# Data card ({cfg['data']['mode']} data)\n\nNo cleaning report: rerun "
                "`scripts/01_prepare_data.py` without `--no-report` to fill this card.\n")
    h = clean.get("category_harmonisation")
    removed = [[k.replace("_", " "), n(v)] for k, v in clean["removed"].items()]
    sess = [[k, n(v["eligible"]), f"{v['positive_rate']:.1%}"] for k, v in sorted(d["sessionize"].items(), key=lambda x: int(x[0]))]
    mp = store.csv("monthly_profile")
    months = [[r["month"], n(r["events"]), n(r["sessions"]), f"{r['conversion']:.2%}"]
              for r in mp.iter_rows(named=True)] if mp is not None else []
    rules = cfg["data"]["cleaning"]
    lines = [
        f"# Data card: REES46 multi-category store ({cfg['data']['mode']} data)",
        "",
        f"*Generated by `scripts/08_model_cards.py` on {date.today():%d %B %Y}. Do not edit by hand.*",
        "",
        "## Source",
        "- Public event log of a large multi-category online shop, published by the REES46 marketing platform "
        "(Kaggle: *eCommerce behavior data from multi category store*). See the dataset page for its terms of use.",
        "- One row per event: `event_time` (UTC), `event_type` (view, cart, remove_from_cart, purchase), `product_id`, "
        "`category_id`, `category_code`, `brand`, `price`, `user_id`, `user_session`.",
        f"- Files used: {', '.join(clean['sources'])}.",
        "",
        "## Size after cleaning",
        f"- {n(clean['rows_out'])} events, {n(clean['sessions_out'])} visits, {n(clean['purchase_sessions_out'])} "
        f"visits with a purchase ({clean['purchase_sessions_out'] / clean['sessions_out']:.2%}).",
        f"- Raw input: {n(clean['rows_in'])} events, {n(clean['sessions_in'])} visits.",
        "",
    ]
    if months:
        lines += ["Per month:", "", table(months, ["Month", "Events", "Visits", "Visits that buy"]), ""]
    lines += ["## Cleaning (rows removed, in order)", "", table(removed, ["Step", "Rows removed"]), "",
              f"- Session sampling keeps a random {clean['sessions_out'] / clean['sessions_in']:.0%} of whole visits by "
              "hashing the session id (deterministic, seed = first project seed); counts are the sample's, rates "
              "represent the shop.",
              f"- Prices ≤ {rules['min_price']} removed; visits longer than {rules['max_session_duration_hours']} h "
              "treated as logging artefacts.", ""]
    if h:
        lines += ["## Category harmonisation",
                  "- On 1 December 2019 the log switches to a new category tree whose labels do not describe the "
                  "products (for example iPhones under `construction.tools.light`).",
                  "- Each product is mapped back to its own Oct/Nov 2019 label, or through its new category id to the "
                  "Oct/Nov label most of that id's products had (≥ 60 % agreement, ≥ 3 products). `src/data/categories.py`.",
                  f"- {n(h['products_labelled'])} of {n(h['products'])} products have a category after mapping; the rest "
                  "never had one and stay `unknown`.", ""]
    lines += ["## Task construction",
              "- Each visit is cut after its first K events; visits that buy within those K events are dropped so the "
              "answer is never in the input. Target: does the visit end in a purchase.", "",
              table(sess, ["K", "Usable visits", "Buy later"]), "",
              "- Split by visit start time (70 / 15 / 15 %), with visits that straddle a boundary removed.", "",
              "## Known issues",
              "- Many products have no category or brand (`unknown`).",
              "- `remove_from_cart` never occurs in this shop's log, so the related feature is always 0.",
              "- Holiday season (Nov–Dec) and early 2020 behave differently; models are tested on later weeks only.",
              "",
              "## Personal data",
              "- `user_id` and `user_session` are pseudonymous identifiers; no names, contacts or demographics exist in "
              "the data. Neither identifier is used as a model input."]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    p = base_parser(__doc__.splitlines()[0])
    p.add_argument("--k", type=int, help="K for the model card (default: sessionize.default_k)")
    args = p.parse_args(argv)
    cfg = setup(args)
    store = ResultStore(cfg)
    k = args.k or int(cfg["sessionize"]["default_k"])
    out = PROJECT_ROOT / "docs"
    out.mkdir(exist_ok=True)
    mode = cfg["data"]["mode"]
    (out / f"model_card_{mode}.md").write_text(model_card(store, cfg, k))
    (out / f"data_card_{mode}.md").write_text(data_card(store, cfg))
    print(f"Wrote docs/model_card_{mode}.md and docs/data_card_{mode}.md")


if __name__ == "__main__":
    main()
